/** เดือน 'YYYY-MM' (DETAIL ของ AG010) → "มีนาคม 2027" · รูปแบบแปลก = null (ไม่เดา) */
function detailMonth(details: string | null | undefined): string | null {
  const m = /^(\d{4})-(0[1-9]|1[0-2])$/.exec((details ?? "").trim());
  return m ? monthLabel(`${m[1]}-${m[2]}`) : null;
}

/** วันที่ 'YYYY-MM-DD' (DETAIL ของ AG013) → "1 เมษายน 2027" · รูปแบบแปลก = null */
function detailDate(details: string | null | undefined): string | null {
  const m = /^(\d{4})-(0[1-9]|1[0-2])-(\d{2})$/.exec((details ?? "").trim());
  return m ? `${Number(m[3])} ${monthLabel(`${m[1]}-${m[2]}`)}` : null;
}

/** AG010 (M28): เลือก 1 ใน 3 สาเหตุจากข้อความของ DB แล้วใส่เดือนสุดท้ายที่ Renew ได้ (DETAIL) */
function describeGapError(error: DbErrorLike): string {
  const msg = (error.message ?? "").toLowerCase();
  const until = detailMonth(error.details);
  if (msg.includes("after the old contract starts")) {
    return "วันเริ่มสัญญาใหม่ต้องอยู่หลังวันเริ่มสัญญาเก่า — ตรวจวันที่ หรือเปิดเป็นลูกค้าใหม่ (New)";
  }
  if (msg.includes("linked renewal")) {
    return until
      ? `แก้วันที่ของสัญญานี้ไม่ได้ — สัญญาที่ต่อ (Renew) จากสัญญานี้จะเริ่มเกินช่วง (ต้องเริ่มไม่เกิน ${until})`
      : "แก้วันที่ของสัญญานี้ไม่ได้ — สัญญาที่ต่อ (Renew) จากสัญญานี้จะเริ่มเกิน 2 เดือนหลังสัญญาจบ";
  }
  return until
    ? `สัญญาใหม่เริ่มเกิน 2 เดือนหลังสัญญาเก่าจบ — Renew ได้ถึง ${until} เท่านั้น ถ้าเริ่มหลังจากนั้นให้เปิดเป็นลูกค้าใหม่ (New)`
    : "สัญญาใหม่เริ่มเกิน 2 เดือนหลังสัญญาเก่าจบ — ให้เปิดเป็นลูกค้าใหม่ (New)";
}

/** AG008 = มีคนแก้สัญญานี้ไปก่อน (กันเขียนทับ M12) — หน้าจอแสดงปุ่ม "โหลดแถวใหม่" */
export const CONFLICT_ERROR_CODE = "AG008";

/** 22004 = หน้าจอลืมส่งเวลาแก้ล่าสุด (บั๊กของหน้าจอ ไม่ใช่ความผิดผู้ใช้) */
const MISSING_EXPECTED_MESSAGE =
  "ระบบไม่ได้รับเวลาแก้ล่าสุดของสัญญา (ข้อผิดพลาดของหน้าจอ) กรุณาโหลดแถวใหม่ หากยังไม่ได้ให้แจ้งผู้ดูแลระบบ";

export function describeDbError(error: DbErrorLike, context: ErrorContext = "save"): string {
  const code = error.code ?? "";
  const msg = (error.message ?? "").toLowerCase();
  const status = String(error.statusCode ?? "");

  // M28: สองรหัสนี้ต้องใช้ DETAIL ใส่ในข้อความ จึงตรวจก่อนตารางข้อความตายตัว
  if (code === "AG010") return describeGapError(error);
  if (code === "AG013") {
    const from = detailDate(error.details);
    return `หมดช่วงที่เปิด Renew แบบไม่ผูกสัญญาเก่าแล้ว${from ? ` (ตั้งแต่ ${from})` : ""} — ผูกสัญญาเก่าที่ต่อมา หรือเปิดเป็นลูกค้าใหม่ (New)`;
  }

  // M26/M33: ทีมปิด (TM004) / ทีมหัวหน้างาน (TM005) / เปิด-ปิดทีม (TM006) — มี DETAIL = รหัสทีม
  const teamMessage = describeTeamError(code, error.details);
  if (teamMessage) return teamMessage;

  // M28b: AG014 ตอนปิดรายการ = ไม่ใช่ Renew ที่ยังไม่ผูก (ข้อความในตารางเป็นของการเชื่อมสัญญาเก่า)
  if (code === "AG014" && context === "close") {
    return "ปิดรายการได้เฉพาะสัญญา Renew ที่ยังไม่ผูกสัญญาเก่า — รีเฟรชหน้าเพื่อดูสถานะล่าสุด";
  }

  // รหัสของ RPC บันทึก/ลบสัญญา (AG001–AG015) — ตรวจก่อน เพราะ PostgREST ตอบ HTTP 400
  const rpcMessage = RPC_ERRORS[code];
  if (rpcMessage) return rpcMessage;
  if (code === "22004") return MISSING_EXPECTED_MESSAGE;

  if (
    code === "42501" ||
    status === "403" ||
    msg.includes("row-level security") ||
    msg.includes("permission denied") ||
    msg.includes("violates row-level") ||
    msg.includes("unauthorized")
  ) {
    if (context === "file") {
      return "ไม่มีสิทธิ์จัดการไฟล์ของสัญญานี้ (สัญญาอาจอยู่นอกขอบเขตของบัญชี หรือสัญญาถูกปิดแล้ว)";
    }
    if (context === "link" || context === "close") {
      return `ไม่มีสิทธิ์${context === "link" ? "เชื่อมสัญญาเก่า" : "ปิดรายการ"}นี้ — สัญญานี้อยู่นอกขอบเขตของบัญชีคุณ`;
    }
    return context === "delete"
      ? "ไม่มีสิทธิ์ลบสัญญานี้ — สาขานี้อยู่นอกขอบเขตของบัญชีคุณ"
      : "ไม่มีสิทธิ์บันทึกข้อมูลนี้ — สาขานี้อยู่นอกขอบเขตของบัญชีคุณ";
  }
  if (code === "23505" || msg.includes("duplicate") || status === "409") {
    return context === "file"
      ? "มีไฟล์ชื่อนี้อยู่แล้ว ลองอีกครั้ง"
      : "เลขที่สัญญานี้มีอยู่ในระบบแล้ว";
  }
  if (code === "23503") {
    if (context === "save" && msg.includes("renewed_from")) {
      return "ไม่พบสัญญาเก่าที่ผูกไว้ (อาจถูกลบไปแล้ว) เลือกสัญญาเก่าใหม่";
    }
    return "ลบไม่ได้ เพราะมีผลบริการหรือข้อมูลที่อ้างอิงอยู่แล้ว (ให้ใช้สถานะยกเลิกแทน)";
  }
  if (code === "23514") {
    if (msg.includes("first_service_time")) return "ใส่เวลาบริการได้เมื่อมีวันที่บริการ เลือกวันที่ก่อน";
    if (msg.includes("renewed_from_itself")) return "สัญญาผูกกับตัวเองไม่ได้ เลือกสัญญาเก่าอีกใบ";
    return "ข้อมูลไม่ผ่านเงื่อนไขของระบบ ตรวจค่าที่กรอกอีกครั้ง";
  }
  if (code === "P0001") {
    if (msg.includes("same customer")) {
      return "Renew ต้องผูกกับสัญญาเก่าของลูกค้าคนเดียวกัน เลือกสัญญาเก่าใหม่";
    }
    if (msg.includes("closed")) return "สัญญานี้ปิดแล้ว ไฟล์ถูกล็อก เพิ่ม/แก้/ลบไม่ได้";
    if (msg.includes("attach the contract pdf")) {
      return "ต้องแนบ PDF สัญญาก่อน จึงจะอัปเดต Site plan ได้";
    }
    return "ระบบไม่อนุญาตการกระทำนี้";
  }
  if (msg.includes("failed to fetch") || msg.includes("network")) {
    return "เชื่อมต่อเซิร์ฟเวอร์ไม่ได้ ตรวจอินเทอร์เน็ตแล้วลองอีกครั้ง";
  }
  if (msg.includes("mime") || msg.includes("not supported")) {
    return "ชนิดไฟล์นี้ระบบไม่รับ";
  }
  if (msg.includes("exceeded") || msg.includes("too large") || status === "413") {
    return "ไฟล์ขนาดใหญ่เกินไป";
  }
  return "บันทึกไม่สำเร็จ ลองอีกครั้ง หากยังไม่ได้ให้แจ้งผู้ดูแลระบบ";
}
