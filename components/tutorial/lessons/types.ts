/**
 * ชนิดข้อมูลของบทเรียนเริ่มใช้งาน (E1) — ข้อมูลล้วน ไม่มีตรรกะ
 *
 * บทเรียน 1 ไฟล์ต่อกลุ่มตำแหน่ง (position_code) + ไฟล์ส่วนกลาง (ล็อกอิน/เปลี่ยนรหัส)
 * เพิ่มตำแหน่งใหม่/แก้ข้อความ = แก้ไฟล์ในโฟลเดอร์นี้ ไม่ต้องแตะโค้ดตัวแสดงกล่อง
 *
 * แต่ละขั้นชี้ไปที่ element ด้วย attribute `data-tour="<target>"` ในหน้าจริง
 * (ถ้าหา element ไม่เจอ ตัวแสดงจะข้ามขั้นนั้นไปเงียบๆ)
 */

/** รหัสบทเรียน: ส่วนกลาง + 3 กลุ่มตำแหน่ง */
export type LessonId = "central" | "admin" | "recorder" | "pmom";

/**
 * หน้าจอของขั้นนั้น
 *  - `app`           = หน้าจริงของระบบ (ใช้ `path` พาไป)
 *  - `sandbox-login` / `sandbox-chpw` = หน้าจำลองของบทเรียนส่วนกลาง (หน้าเข้าสู่ระบบ/เปลี่ยนรหัสจริงอยู่นอก
 *    โครงหน้าหลัก และผู้ใช้ผ่านมาแล้ว จึงจำลองไว้ฝึก — ไม่เรียกระบบจริง)
 */
export type StepScreen = "app" | "sandbox-login" | "sandbox-chpw";

export type LessonStep = {
  /** ค่าเริ่มต้น `app` */
  screen?: StepScreen;
  /** เส้นทางที่ต้องอยู่ (เฉพาะ `app`) — ไม่ระบุ = อยู่หน้าไหนก็ได้ (เช่น ชี้เมนูซ้าย) */
  path?: string;
  /** ค่า `data-tour` ของ element ที่ชี้ · null = ไม่ชี้จุด (กล่องอยู่กลางจอ) */
  target: string | null;
  /** `click` = ให้ผู้ใช้ลองกดจุดที่ไฮไลต์ (ปุ่มถัดไปกลายเป็น “ข้ามขั้นนี้”) */
  act?: "click";
  /** `pw` = ต้องกรอกรหัสผ่านตัวอย่างให้ผ่านเงื่อนไขก่อนไปต่อ (เฉพาะหน้าจำลอง) */
  guard?: "pw";
  title: string;
  body: string;
  /** ข้อความแนะนำสีน้ำเงินใต้เนื้อหา */
  hint?: string;
  /** ข้อความปุ่มหลักแทน “ถัดไป / เสร็จสิ้น” */
  cta?: string;
  /**
   * จุดสำรอง: ถ้าหา `target` ไม่เจอ (เช่น ฟอร์มยังไม่โผล่เพราะยังไม่ได้เลือกลูกค้า) ให้ชี้จุดนี้พร้อมข้อความนี้แทน
   * (เป็นขั้นอ่านธรรมดา ไม่ให้ลองกด) · หาจุดสำรองไม่เจอด้วย = ข้ามขั้นเงียบๆ
   */
  fallback?: { target: string; title?: string; body: string; hint?: string };
};

export type Lesson = {
  id: LessonId;
  title: string;
  /** ตำแหน่งที่เป็นเจ้าของบทเรียน (ชื่อที่ผู้ใช้เห็น ใช้แสดงเฉยๆ) */
  positions: readonly string[];
  /** `@position` = จบแล้วต่อด้วยบทเรียนของตำแหน่งผู้ใช้ */
  next?: "@position";
  steps: readonly LessonStep[];
};
